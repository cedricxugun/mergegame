"""Read alpha bounds and write renderer metadata; never alter source pixels."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
CONFIG = {**{f'craft-{c}-atlas': (4, 2, 7) for c in ('wood', 'water', 'reed', 'dock')},
          'craft-ruins-atlas': (3, 2, 6), 'craft-camp-scenes-v14': (2, 2, 4),
          'craft-river-scenes-v14': (3, 2, 6), 'craft-forest-props-v14': (2, 2, 4)}
# The source artwork has six independent silhouettes, with a few intentional
# overhangs beyond the nominal grid. These measured rectangles exclude neighbors.
OVERRIDES = {'craft-river-scenes-v14': [[16,64,504,488],[510,40,1060,504],[1084,68,1516,472],
                                      [22,512,514,966],[544,576,976,945],[1020,508,1528,970]]}
result = {}
for name, (cols, rows, count) in CONFIG.items():
    image = Image.open(ROOT / 'dist' / 'assets' / (name + '.png')).convert('RGBA')
    width, height = image.size
    alpha = image.getchannel('A')
    frames = []
    for index in range(count):
        if name in OVERRIDES:
            rect = OVERRIDES[name][index]
        else:
            col, row = index % cols, index // cols
            bounds = (round(col*width/cols), round(row*height/rows), round((col+1)*width/cols), round((row+1)*height/rows))
            box = alpha.crop(bounds).point(lambda a: 255 if a > 8 else 0).getbbox()
            if not box:
                raise ValueError(f'Empty frame {name}:{index}')
            rect = [max(bounds[0], bounds[0]+box[0]-8), max(bounds[1], bounds[1]+box[1]-8),
                    min(bounds[2], bounds[0]+box[2]+8), min(bounds[3], bounds[1]+box[3]+8)]
        left, top, right, bottom = rect
        assert 0 <= left < right <= width and 0 <= top < bottom <= height
        frames.append([left, top, right-left, bottom-top])
    result[name] = {'width': width, 'height': height, 'frames': frames}
(ROOT / 'dist' / 'homecoming-art-frames.mjs').write_text(
    '// Native PNG coordinates, measured from alpha. Generated by scripts/measure-art-frames.py.\n'
    + 'export const ART_FRAMES=' + json.dumps(result, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'Measured {sum(len(v["frames"]) for v in result.values())} frames; source PNGs unchanged.')
